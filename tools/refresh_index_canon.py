"""Regenerate ``openbb_wmshare/utils/_index_canon.json`` from the airflow registry.

The index alias table (``index.hs300`` -> ``399300.INDEX``) is owned upstream by
the airflow repo. This tool snapshots it so the provider can resolve aliases
without a runtime cross-repo dependency.

Usage::

    python tools/refresh_index_canon.py            # rewrite the snapshot
    python tools/refresh_index_canon.py --check    # fail if out of date

Exits 2 when the upstream registry is absent (a sibling checkout is not
guaranteed), matching the skip-not-fail convention used by wmshare's own
extraction tools.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT.parent / "airflow" / "catalog" / "index_registry_live.json"
TARGET = ROOT / "openbb_wmshare" / "utils" / "_index_canon.json"


def build_payload(source: Path) -> dict:
    """Read the airflow registry and reduce it to the packaged snapshot."""
    raw = json.loads(source.read_text(encoding="utf-8"))
    canon = raw.get("canon")
    if not isinstance(canon, dict):
        raise SystemExit(f"{source} has no 'canon' mapping")

    # Only canonical bar-store codes are usable; the registry also carries
    # sentinels like {"cnall": "cnall"} that name no tradeable series.
    usable = {
        str(alias).strip(): str(code).strip().upper()
        for alias, code in canon.items()
        if str(code).strip().upper().endswith(".INDEX")
    }
    return {
        "_comment": (
            "Generated by tools/refresh_index_canon.py from "
            "../airflow/catalog/index_registry_live.json. Do not hand-edit."
        ),
        "asof": raw.get("asof"),
        "source": "airflow/catalog/index_registry_live.json#canon",
        "canon": dict(sorted(usable.items())),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when the packaged snapshot differs from upstream",
    )
    args = parser.parse_args(argv)

    if not args.source.is_file():
        print(f"UPSTREAM_UNAVAILABLE: {args.source}", file=sys.stderr)
        return 2

    payload = build_payload(args.source)
    text = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"

    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(
                "DRIFT: _index_canon.json is stale; run python tools/refresh_index_canon.py",
                file=sys.stderr,
            )
            return 1
        print(f"ok: {len(payload['canon'])} aliases, asof {payload['asof']}")
        return 0

    TARGET.write_text(text, encoding="utf-8")
    print(
        f"wrote {TARGET.relative_to(ROOT)}: {len(payload['canon'])} aliases, asof {payload['asof']}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
